"""Generate portable Kaggle entry points from the package; no second model implementation."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render() -> dict[Path, str]:
    paths = [*sorted((ROOT / "pa_recon").glob("*.py")), *sorted((ROOT / "tests").glob("test_*.py")),
             ROOT / "configs/pilot.json", ROOT / "LICENSE",
             *[ROOT / "results/development" / name for name in ("scales.json", "splits.csv", "checkpoint_provenance.json")]]
    # Source text is normalized across checkouts; the archived split is byte-exact.
    files = {p.relative_to(ROOT).as_posix(): (p.read_bytes().decode("utf-8") if p.name == "splits.csv"
                                            else p.read_text(encoding="utf-8")) for p in paths}
    source_hash = hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()
    setup = (
        "from pathlib import Path\nimport json\nimport os\nimport subprocess\nimport sys\n\n"
        "project = Path('/kaggle/working/pa-recon-lab')\n"
        "output = Path('/kaggle/working/pa-recon-results')\n"
        f"source_files = {files!r}\n"
        "for relative, content in source_files.items():\n"
        "    destination = project / relative\n"
        "    destination.parent.mkdir(parents=True, exist_ok=True)\n"
        "    destination.write_text(content, encoding='utf-8', newline='')\n"
        f"print('Embedded source SHA256: {source_hash}')\n"
        "environment = dict(os.environ, PYTHONPATH=str(project), PYTHONUNBUFFERED='1')\n"
    )
    download = (
        "subprocess.run([sys.executable, '-m', 'unittest', 'discover', '-s', 'tests', '-v'],\n"
        "               cwd=project, env=environment, check=True)\n"
        "subprocess.run([sys.executable, '-m', 'pa_recon.cli', 'download-data'],\n"
        "               cwd=project, env=environment, check=True)\n"
    )
    run = (
        "subprocess.run([sys.executable, '-m', 'pa_recon.cli', 'run',\n"
        "                '--config', 'configs/pilot.json', '--output', str(output), '--require-cuda'],\n"
        "               cwd=project, env=environment, check=True)\n"
        "print('Download the pa-recon-results output directory: weights, metrics, splits, scales and manifest.')\n"
    )
    cells = [{"cell_type": "markdown", "id": "overview", "metadata": {}, "source": [
        "# PA Recon Lab: reproducible GPU pilot\n",
        "Compare unaugmented and augmented training on a fixed synthetic development split.\n",
        "Enable GPU and Internet. This uses the repository's own model, CLI, checkpoint format and loss.\n",
        "The 100-sample subset is a pipeline pilot. This notebook requires a CUDA GPU and stops if one is absent.\n",
        "Data: https://doi.org/10.5281/zenodo.21785486 (CC BY 4.0).\n"
    ]}]
    for cell_id, content in (("source", setup), ("download", download), ("experiment", run)):
        cells.append({"cell_type": "code", "id": cell_id, "execution_count": None,
                      "metadata": {}, "outputs": [], "source": content.splitlines(keepends=True)})
    notebook = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                "language_info": {"name": "python"}}, "nbformat": 4, "nbformat_minor": 5}
    script = '# Generated by scripts/build_kaggle_notebook.py; edit the package and rebuild.\n' + setup + '\n' + download + '\n' + run
    return {ROOT / "kaggle_kernel/train.ipynb": json.dumps(notebook, indent=1) + "\n",
            ROOT / "kaggle_kernel/train.py": script}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated entry points are stale")
    args = parser.parse_args()
    stale = []
    for path, content in render().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path.name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit(f"Rebuild Kaggle entry points: {', '.join(stale)}")
    print("Kaggle entry points are current." if args.check else "Built Kaggle notebook and script from the package.")


if __name__ == "__main__":
    main()
